export function fillPolicy(text: string, s: Record<string, string | undefined>) {
  const site = s.site_name || '셀러브릭스 캠퍼스';
  return text
    .split('{site}').join(site)
    .split('{officer}').join(s.privacy_officer || `${site} 운영팀`)
    .split('{contact}').join(s.privacy_contact || '관리자 설정에서 등록해 주세요')
    .split('{date}').join(s.policy_date || POLICY_EFFECTIVE);
}
